import { test, expect, signIn, createSurvey, openSurvey, confirmAction, read, screenshot } from './support/real-app.js';

test('B23-01 real owner → student → closed results, persisted reload/relogin and validation', async ({ page, data }, info) => {
  const title = `Browser ${info.project.name}`;
  await signIn(page);
  const definition = await createSurvey(page, await data.lecture(), title);
  const path = `/api/surveys/${definition.id}`;
  const frozen = page.getByRole('region', { name: 'Frozen questionnaire', exact: true });
  for (const text of ['Understanding', 'Higher means clearer', 'Next time', 'Optional']) await expect(frozen).toContainText(text);
  await expect(frozen.locator('input, textarea, select')).toHaveCount(0);
  await expect(page.getByText('Scores and written feedback become available after closing.', { exact: true })).toBeVisible();
  expect(await read(page, `${path}/results`)).not.toHaveProperty('questions');
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await signIn(page, 'respondent.11@example.test');
  const row = page.getByRole('listitem').filter({ hasText: title });
  for (const text of ['SYN-CPE334', 'Section A', '2026-11-10', 'IDENTIFIED']) await expect(row).toContainText(text);
  await openSurvey(page, title);
  await expect(page.getByText(/This survey is identified\./)).toBeVisible();
  await expect(page.locator('input[type=radio]:checked')).toHaveCount(0);
  const comment = '<script>window.feedbackExecuted=true</script> More examples.';
  const answer = page.getByRole('textbox', { name: 'Written answer for Next time', exact: true });
  await answer.fill(comment);
  await page.getByRole('button', { name: 'Submit feedback', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('INVALID_ANSWERS');
  await expect(page.getByRole('alert')).toBeFocused();
  await expect(answer).toHaveValue(comment);
  const rating = page.getByRole('radio', { name: '5', exact: true });
  await rating.focus(); await page.keyboard.press('Space');
  await expect(rating).toBeChecked();
  await page.getByRole('button', { name: 'Submit feedback', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Submission received', exact: true })).toBeVisible();
  const expected = [{ questionId: definition.questions[0].id, value: 5 }, { questionId: definition.questions[1].id, value: comment }];
  expect((await read(page, `${path}/my-submission`)).answers).toEqual(expected);
  await page.reload(); await openSurvey(page, title);
  await expect(page.getByRole('heading', { name: 'Submission received', exact: true })).toBeVisible();
  await expect(page.getByText(comment, { exact: true })).toBeVisible();
  expect((await read(page, `${path}/my-submission`)).answers).toEqual(expected);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await screenshot(page, info, 'persisted-submission');
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await signIn(page, 'respondent.11@example.test'); await openSurvey(page, title);
  await expect(page.getByRole('heading', { name: 'Submission received', exact: true })).toBeVisible();
  expect((await read(page, `${path}/my-submission`)).answers).toEqual(expected);
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await signIn(page); await openSurvey(page, title);
  const published = await read(page, `${path}/results`);
  expect(Object.keys(published).sort()).toEqual(['responseCount', 'survey']); expect(published.responseCount).toBe(1);
  await expect(page.getByText('Responses: 1', { exact: true })).toBeVisible();
  await expect(page.getByRole('table')).toHaveCount(0);
  await confirmAction(page, 'Close survey');
  await expect(page.getByText('5.00', { exact: true })).toBeVisible();
  const summary = await read(page, `${path}/results`);
  expect(summary.responseCount).toBe(1); expect(summary.questions[0].mean).toBe('5.00');
  expect(summary.questions[0].distribution.map((b: { count: number }) => b.count)).toEqual([0, 0, 0, 0, 1]);
  const bins = page.getByRole('table').getByRole('row');
  for (const [index, bin] of summary.questions[0].distribution.entries()) await expect(bins.nth(index + 1).getByRole('cell').first()).toHaveText(String(bin.count));
  await expect(page.getByText('Responses: 1', { exact: true })).toBeVisible();
  await expect(frozen).toContainText('Understanding'); await expect(frozen.locator('input, textarea, select')).toHaveCount(0);
  await expect(page.getByText(comment, { exact: true })).toBeVisible();
  expect(await page.evaluate(() => 'feedbackExecuted' in window)).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await data.responseRows(definition.id)).toEqual({ participation: 1, bundles: 1, answers: 2 });
  await screenshot(page, info, 'closed-results');
});

test('B23-02 real invalid then keyboard login and one StrictMode bootstrap', async ({ page }) => {
  let bootstraps = 0;
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/auth/session') bootstraps++; });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Log in', exact: true })).toBeEnabled();
  expect(bootstraps).toBe(1);
  await page.getByLabel('Email', { exact: true }).fill('owner.1@example.test');
  await page.getByLabel('Password', { exact: true }).fill('Incorrect synthetic password');
  await page.getByLabel('Password', { exact: true }).press('Enter');
  await expect(page.getByRole('alert')).toContainText('Email or password is incorrect.');
  await expect(page.getByRole('alert')).toBeFocused();
  await expect(page.getByLabel('Email', { exact: true })).toHaveValue('owner.1@example.test');
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('');
  await expect(page.getByRole('button', { name: 'Log in', exact: true })).toBeEnabled();
  await page.getByLabel('Password', { exact: true }).fill(process.env.SEED_OWNER_PASSWORD!);
  await page.getByLabel('Password', { exact: true }).press('Enter');
  await expect(page.getByRole('button', { name: 'Log out', exact: true })).toBeVisible();
  expect((await read(page, '/api/auth/me')).user.role).toBe('OWNER');
});
